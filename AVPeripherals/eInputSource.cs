namespace AVPeripherals;

/// <summary>Represents the input source for a peripheral.</summary>
public enum eInputSource
{
	/// <summary>The input source is unknown.</summary>
	Unknown = -1,
	/// <summary>The input source is HDMI 1.</summary>
	HDMI_1,
	/// <summary>The input source is HDMI 2.</summary>
	HDMI_2,
	/// <summary>The input source is HDMI 3.</summary>
	HDMI_3,
	/// <summary>The input source is HDMI 4.</summary>
	HDMI_4,
	/// <summary>The input source is DisplayPort 1.</summary>
	DisplayPort_1,
	/// <summary>The input source is DisplayPort 2.</summary>
	DisplayPort_2,
	/// <summary>The input source is DisplayPort 3.</summary>
	DisplayPort_3,
	/// <summary>The input source is DisplayPort 4.</summary>
	DisplayPort_4,
	/// <summary>The input source is VGA 1.</summary>
	VGA_1,
	/// <summary>The input source is VGA 2.</summary>
	VGA_2,
	/// <summary>The input source is DVI 1.</summary>
	DVI_1,
	/// <summary>The input source is DVI 2.</summary>
	DVI_2,
	/// <summary>The input source is HDBaseT 1.</summary>
	HDBaseT_1,
	/// <summary>The input source is HDBaseT 2.</summary>
	HDBaseT_2,
	/// <summary>The input source is DTV (air or cable).</summary>
	DTV,
	/// <summary>The input source is a built-in signage player.</summary>
	Signage
}
